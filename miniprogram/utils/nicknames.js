function getNicknames(championId) {
  const list = NICKNAMES[championId] || []
  const seen = {}
  const out = []
  list.forEach(n => {
    const s = String(n || '').trim()
    if (!s) return
    const k = s.toLowerCase()
    if (seen[k]) return
    seen[k] = true
    out.push(s)
  })
  return out
}

function buildSearchText(champ) {
  const parts = [champ.name, champ.title, champ.id, champ.key]
  const nicks = champ.nicknames || getNicknames(champ.id)
  nicks.forEach(n => parts.push(n))
  return parts.filter(Boolean).join(' ').toLowerCase()
}

